    var ATTR_MAP = {
        'data-i18n-html': 'innerHTML',
        'data-i18n-placeholder': 'placeholder',
        'data-i18n-title': 'title',
        'data-i18n-aria-label': 'aria-label',
        'data-i18n-value': 'value'
    };

    window.I18N = TEXTS;

    window.LANG = {
        current: 'en',
        texts: TEXTS,
        supported: ['en', 'cs'],

        normalize: function (tag) {
            tag = String(tag || '').toLowerCase();
            if (tag.indexOf('cs') === 0) { return 'cs'; }
            return 'en';
        },

        detect: function () {
            var tags = (navigator.languages && navigator.languages.length)
                ? navigator.languages
                : [navigator.language || navigator.userLanguage || ''];
            for (var i = 0; i < tags.length; i++) {
                var lang = this.normalize(tags[i]);
                if (lang !== 'en') { return lang; }
            }
            return 'en';
        },

        set: function (lang) {
            this.current = this.supported.indexOf(lang) === -1 ? 'en' : lang;
            document.documentElement.setAttribute('data-lang', this.current);
            document.documentElement.setAttribute('lang', this.current);
            this.apply();

            var indicator = document.getElementById('lang-indicator');
            if (indicator) { indicator.textContent = this.current.toUpperCase(); }
        },

        apply: function () {
            var texts = this.texts[this.current] || {};

            document.querySelectorAll('[data-i18n]').forEach(function (el) {
                var value = texts[el.getAttribute('data-i18n')];
                if (value !== undefined) { el.textContent = value; }
            });

            Object.keys(ATTR_MAP).forEach(function (dataAttr) {
                var target = ATTR_MAP[dataAttr];
                document.querySelectorAll('[' + dataAttr + ']').forEach(function (el) {
                    var value = texts[el.getAttribute(dataAttr)];
                    if (value === undefined) { return; }
                    if (target === 'innerHTML') { el.innerHTML = value; }
                    else { el.setAttribute(target, value); }
                });
            });
        },

        init: function () {
            var saved = null;
            try { saved = localStorage.getItem('lang'); } catch (e) { /* private mode */ }
            this.set(saved || this.detect());
        },

        toggle: function () {
            this.set(this.current === 'en' ? 'cs' : 'en');
            try { localStorage.setItem('lang', this.current); } catch (e) { /* ignore */ }
        }
    };

    // The script lives in <head>, so the DOM is not ready yet.
    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', function () { window.LANG.init(); });
    } else {
        window.LANG.init();
    }
